def write_strings(lang: str, mapping: dict):
    folder = os.path.join(RES, f"{lang}.lproj")
    os.makedirs(folder, exist_ok=True)
    path = os.path.join(folder, "Localizable.strings")
    lines = []
    extra_keys = sorted(k for k in mapping if k not in STRINGS)
    for key in list(STRINGS.keys()) + extra_keys:
        value = mapping.get(key, STRINGS.get(key, ""))
        escaped = value.replace('"', '\\"').replace('\n', '\\n')
        lines.append(f'"{key}" = "{escaped}";')
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    write_info_plist_strings(lang, mapping.get("app.title", STRINGS["app.title"]))


def write_info_plist_strings(lang: str, display_name: str):
    folder = os.path.join(RES, f"{lang}.lproj")
    os.makedirs(folder, exist_ok=True)
    path = os.path.join(folder, "InfoPlist.strings")
    escaped = display_name.replace('"', '\\"')
    with open(path, "w", encoding="utf-8") as f:
        f.write(f'CFBundleDisplayName = "{escaped}";\n')


def batch_translate(target: str) -> dict:
    items = [STRINGS[k] for k in STRINGS]
    payload = "\n".join(f"[{i+1}] {v}" for i, v in enumerate(items))
    target_label = TARGET_LANG_NAMES.get(target, target)
    try:
        result = subprocess.run(
            ["python3", TRANSLATE_SCRIPT, payload, "-s", "en", "-t", target_label],
            capture_output=True, text=True, timeout=180, check=True,
        )
        lines = result.stdout.strip().splitlines()
        translated = {}
        for i, key in enumerate(STRINGS):
            if i < len(lines):
                line = lines[i]
                if "]" in line:
                    line = line.split("]", 1)[1].strip()
                translated[key] = line
            else:
                translated[key] = STRINGS[key]
        return translated
    except Exception as e:
        print(f"Translation failed for {target}: {e}", file=sys.stderr)
        return STRINGS.copy()


def read_strings(path: str) -> dict:
    mapping = {}
    if not os.path.exists(path):
        return mapping
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line.startswith('"'):
                continue
            parts = line.split('"')
            if len(parts) >= 4:
                mapping[parts[1]] = parts[3]
    return mapping


def sync_locales(base_en: dict, zh_overrides: dict, zh_hant_overrides: dict):
    """Fill missing keys in every locale from en/zh-Hans without re-translating."""
    for lang in LANGS:
        folder = os.path.join(RES, f"{lang}.lproj")
        path = os.path.join(folder, "Localizable.strings")
        existing = read_strings(path)
        merged = dict(base_en)
        merged.update(existing)
        if lang == "zh-Hans":
            merged.update(zh_overrides)
        if lang == "zh-Hant":
            merged.update(zh_hant_overrides)
        for key in STRINGS:
            if key not in merged:
                merged[key] = base_en.get(key, STRINGS[key])
        for key, value in existing.items():
            if key not in STRINGS and key not in merged:
                merged[key] = value
        write_strings(lang, merged)
    print("Synced all locale files.")


def main():
    write_strings("en", STRINGS)
    write_strings("zh-Hans", {**STRINGS, **ZH_HANS})
    sync_locales(STRINGS, ZH_HANS, ZH_HANT)

    if "--full-translate" not in sys.argv:
        print("Done (sync only). Pass --full-translate to regenerate all languages via API.")
        return

    for lang in LANGS:
        if lang in ("en", "zh-Hans"):
            continue
        print(f"Generating {lang}...")
        mapping = batch_translate(lang)
        write_strings(lang, mapping)

    print("Done.")


if __name__ == "__main__":
    main()
