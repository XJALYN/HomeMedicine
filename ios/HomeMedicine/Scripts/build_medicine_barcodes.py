def ean13_check_digit(body12: str) -> str:
    total = sum(int(ch) * (1 if i % 2 == 0 else 3) for i, ch in enumerate(body12))
    return str((10 - (total % 10)) % 10)


def normalize_ean13(code: str) -> str:
    digits = "".join(ch for ch in code if ch.isdigit())
    if len(digits) == 12:
        digits = "0" + digits
    if len(digits) == 13:
        body = digits[:12]
        return body + ean13_check_digit(body)
    return digits


def main() -> None:
    products = []
    seen: set[str] = set()
    for barcode, name, spec, manufacturer, approval, is_otc in RECORDS:
        barcode = normalize_ean13(barcode)
        if barcode in seen or len(barcode) != 13:
            continue
        seen.add(barcode)
        products.append(
            {
                "barcode": barcode,
                "name": name,
                "specification": spec,
                "manufacturer": manufacturer,
                "approvalNumber": approval,
                "isOTC": is_otc,
            }
        )

    payload = {
        "version": 1,
        "source": "bundled verified OTC barcodes (39.net / 315jiage.cn public listings)",
        "count": len(products),
        "products": products,
    }
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"Wrote {len(products)} products to {OUT}")


if __name__ == "__main__":
    main()
